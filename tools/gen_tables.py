#!/usr/bin/env python3
"""Generate ACME data tables (keyword/token table, immediate-command table,
error-message table, indent tables) mechanically from R.T. Russell's
BBC BASIC (Z80) v5 source file MAIN.Z80 (zlib licence).

Usage: gen_tables.py path/to/MAIN.Z80 > src/tables.a

The data is reproduced byte-for-byte, so token values, keyword order,
abbreviation behaviour and error numbers/texts are identical to upstream.
"""
import re, sys

src = open(sys.argv[1], encoding='latin-1').read().splitlines()

# symbol table for the EQUs used inside the tables
equ = {}
for ln in src:
    m = re.match(r'^([A-Z][A-Z0-9]*)\s+EQU\s+([0-9A-F]+)H\s*(;.*)?$', ln)
    if m:
        equ[m.group(1)] = int(m.group(2), 16)

def val(tok):
    tok = tok.strip()
    if re.fullmatch(r'[0-9][0-9A-F]*H', tok):
        return int(tok[:-1], 16)
    if re.fullmatch(r'-?[0-9]+', tok):
        return int(tok) & 0xFFFF
    if tok in equ:
        return equ[tok]
    raise ValueError(tok)

def parse_defm(arg):
    # 'text' with '' as escaped quote
    arg = arg.strip()
    assert arg[0] == "'" and arg[-1] == "'", arg
    return arg[1:-1].replace("''", "'").encode('latin-1')

def grab(start_label, stop_pred):
    out = []
    started = False
    for ln in src:
        code = ln.split(';')[0] if "'" not in ln else ln
        if not started:
            if ln.startswith(start_label + ':'):
                started = True
                ln = ln[len(start_label) + 1:]
            else:
                continue
        elif stop_pred(ln):
            break
        # strip label
        m = re.match(r'^([A-Z][A-Z0-9]*:)?\s*(DEFB|DEFM|DEFW)\s+(.*)$', ln.strip() if not ln[0:1].isalpha() else ln)
        if not m:
            m = re.match(r'^\s*(DEFB|DEFM|DEFW)\s+(.*)$', ln)
            if not m:
                continue
            op, arg = m.group(1), m.group(2)
        else:
            op, arg = m.group(2), m.group(3)
        if op == 'DEFM':
            # cut trailing comment after closing quote
            q = arg.rfind("'")
            out += list(parse_defm(arg[:q + 1]))
        else:
            arg = arg.split(';')[0]
            for a in arg.split(','):
                v = val(a)
                if op == 'DEFB':
                    out.append(v & 0xFF)
                else:
                    out += [v & 0xFF, (v >> 8) & 0xFF]
    return out

def emit(name, data):
    print(f'{name}')
    for i in range(0, len(data), 16):
        print('\t!byte ' + ','.join(f'${b:02x}' for b in data[i:i + 16]))

kw = grab('KEYWDS', lambda l: l.startswith('KEYWDL'))
cm = grab('COMNDS', lambda l: l.startswith(';'))
er = grab('ERRWDS', lambda l: l.startswith(';Indent'))
ta = grab('TOKADD', lambda l: l.startswith('LENADD'))
ts = grab('TOKSUB', lambda l: l.startswith('LENSUB') or l.startswith(';'))

print('; *** GENERATED by tools/gen_tables.py from BBC BASIC (Z80) v5 MAIN.Z80')
print('; *** (C) R.T. Russell, zlib licence. Do not edit by hand.')
emit('KEYWDS', kw)
print(f'KEYWDL = {len(kw)}')
print('\t!word $ffff')
emit('COMNDS', cm + [0xff, 0xff])
emit('ERRWDS', er)
emit('TOKADD', ta)
print(f'LENADD = {len(ta)}')
emit('TOKSUB', ts)
print(f'LENSUB = {len(ts)}')
for k in sorted(equ):
    if k.startswith('T') and equ[k] < 256:
        print(f'{k} = ${equ[k]:02x}')
