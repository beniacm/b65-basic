#!/usr/bin/env python3
"""Generate src/hit65.a: B65's HITPIX (src/hitpix.a) for OBJ65X, the
second module of the BASIC 65 library: the arguments from a parameter
block instead of BASIC text (hpa, hpb: objects a, b; hpdx, hpdy: the move
of a), the result in A (1 / 0; $FF: an object number out of range), the
buffers and records inside the module, the zero page names of B65 put on
the module's own base page. Run by tools/fixbranches.py before it
assembles src/obj65x.a."""
import os, re
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
t = open(os.path.join(ROOT, 'src/hitpix.a')).read()

def rep(a, b, n=1):
    global t
    assert t.count(a) == n, (a[:60], t.count(a))
    t = t.replace(a, b)

i0 = t.index('o_hitpix:')
i1 = t.index('        ldx #24\n        jsr .hrec')
t = t[:i0] + """hit65:  lda hpb                 ; (the arguments: the parameter block)
        sta acc
        lda hpb+1
        sta acc+1
        jsr .nacc
        bcs .hbd
        ldx #24
        jsr .hrec
        lda hpa
        sta acc
        lda hpa+1
        sta acc+1
        jsr .nacc
        bcs .hbd
        ldx #0
        jsr .hrec
        ldx #3
-       lda hpdx,x
        sta hdx,x
        dex
        bpl -
        bra .hgo
.hbd    lda #$ff                ; object number out of range
        rts
.hgo
""" + t[t.index('        clc\n        lda HR\n        adc hdx'):]
rep("""; .N: object number in acc -> objn, fptr = its entry (as OBJ...'s)
.nacc   lda acc+2
        ora acc+3
        bne .bad
        lda acc+1""", """; .NACC: object number acc (16 bits) -> fptr = its entry; carry set if
; it is 1024 or more
.nacc   lda acc+1""")
rep(""".bad    lda #15                 ; Bad subscript (object number 0..1023)
        jmp error""", """.bad    sec
        rts""")
rep("""        lda objbase+3
        sta fptr+3
        ldz #0
        rts""", """        lda objbase+3
        sta fptr+3
        ldz #0
        clc
        rts""")
rep(""".hno    ldz #0
        jmp f_false
.hyes   ldz #0
        jmp f_true""", """.hno    ldz #0
        lda #0
        rts
.hyes   ldz #0
        lda #1
        rts""")
rep("HR      = NUMBUF ", "HR      = hrec65 ")
rep("HB      = $fd00 ", "HB      = hbuf65 ")
rep('!if ovl_xtra_end > HB { !error "overlay 2 runs into HITPIX\'s buffers" }\n', '', t.count('!if ovl_xtra_end > HB'))
t = t.replace('!zone hitpix', '!zone hitpix            ; (generated by tools/mkhit65.py from src/hitpix.a)', 1)
open(os.path.join(ROOT, 'src/hit65.a'), 'w').write(
    '; B65 BASIC - generated from src/hitpix.a by tools/mkhit65.py: do not edit\n' + t + '\n')
print('src/hit65.a written')
