#!/usr/bin/env python3
"""Generate src/objfar.a: B65's frame integrator (src/obj.a, zone objstep)
with the object table read through a 32-bit pointer ([oP],z) instead of
the MAP window at $E000 -- the form the OBJ65 library for BASIC 65 needs
(BASIC 65's interrupt cannot restore the KERNAL's MAP). Y as the index of
(oP),y/(oQ),y becomes Z; Y stays where an absolute ",y" table uses it.
The window loop and the object number in .KILL are replaced. Built into
B65 with ACMEFLAGS=-DOBJFAR=1 (for the measurement and objcheck)."""
import os, re, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = open(os.path.join(ROOT, 'src/obj.a')).read().split('\n')
a = next(i for i, l in enumerate(src) if l.startswith('!zone objstep'))
b = next(i for i, l in enumerate(src) if l.startswith('!zone obj_end'))
body = src[a:b]

YOPS = {'ldy': 'ldz', 'iny': 'inz', 'dey': 'dez', 'tay': 'taz', 'tya': 'tza',
        'cpy': 'cpz', 'sty': 'stz', 'phy': 'phz', 'ply': 'plz'}
def op(l):
    m = re.match(r'^(\S*\s+)?(\w{3})\b(.*)$', l)
    if not m or (m.group(1) or '').strip().startswith(';'):
        return None, None, None
    return m.group(1) or '', m.group(2), m.group(3)

def uses_abs_y(lines, i):
    """does the Y value set at line i reach an absolute ',y' use?"""
    for l in lines[i + 1:]:
        lab, o, rest = op(l)
        if o is None:
            continue
        code = rest.split(';')[0]
        if re.search(r',\s*y\b', code) and not re.search(r'\(o[PQ]\)\s*,\s*y', code):
            return True
        if o in YOPS and o not in ('iny', 'dey', 'cpy', 'sty', 'phy', 'tya'):
            return False            # Y set again
        if o in ('rts', 'jmp', 'bra', 'lbra') or o.startswith('jsr'):
            return False
    return False

out = []
keep = False
for i, l in enumerate(body):
    lab, o, rest = op(l)
    if o in YOPS:
        if o in ('ldy', 'tay', 'ply'):
            keep = uses_abs_y(body, i)
        if not keep:
            l = (lab or '') + YOPS[o] + rest
    l = re.sub(r'\(oP\)\s*,\s*y', '[oP],z', l)
    l = re.sub(r'\(oQ\)\s*,\s*y', '[oQ],z', l)
    out.append(l)
# drop a doubled Z op (the spring had "tay / taz", "iny / inz")
res = []
for l in out:
    if res:
        p = res[-1].split(';')[0].split()
        c = l.split(';')[0].split()
        if c and p and c == p and c[0] in ('taz', 'inz', 'dez'):
            continue
    res.append(l)
text = '\n'.join(res)

def rep(a, b, n=1):
    global text
    assert text.count(a) == n, (a[:60], text.count(a))
    text = text.replace(a, b)

# the window loop -> a 32-bit pointer walk
i0 = text.index('.win    lda oW')
i1 = text.index('.ent    ldz #16')
text = text[:i0] + """        ldx #3                  ; oP = objbase (32 bits)
-       lda objbase,x
        sta oP,x
        dex
        bpl -
""" + text[i1:]
i0 = text.index('.nx     lda oP')
i1 = text.index('.done   lda #0')
text = text[:i0] + """.nx     lda oP                  ; next entry (32 bits)
        clc
        adc #32
        sta oP
        bcc +
        inc oP+1
        bne +
        inc oP+2
+       lda oL                  ; objects left
        bne +
        dec oL+1
+       dec oL
        lda oL
        ora oL+1
        lbne .ent
""" + text[i1:]
rep("""        lda curovl
        jsr ovmap
""", "")
# .KILL: byte = (oP - objbase) / 256 (objbase is page aligned)
rep("""        lda oW                  ; byte = window * 32 + (oP - $E000) / 256
        asl
        asl
        asl
        asl
        asl
        sta oT
        lda oP+1
        sec
        sbc #$e0
        ora oT
        tax""", """        lda oP+1                ; byte = (oP - objbase) / 256
        sec
        sbc objbase+1
        tax""")
# the sine table: a far table (oQ+2/+3 = its bank)
rep("""        sta oQ+1
        ldz #0                  ; (bank 0; the multiplier's high bytes are""",
    """        sta oQ+1
        lda #^SINTAB
        sta oQ+2
        lda #0
        sta oQ+3
        ldz #0                  ; (far; the multiplier's high bytes are""")
text = text.replace('!zone objstep', '!zone objstep          ; (generated by tools/mkobjfar.py)', 1)
text = text.replace('\n.out    pla\n        tab\n        plp\n        rts', '\n.out    pla\n        tab\n        plp\n        ldz #0\n        rts', 1)
open(os.path.join(ROOT, 'src/objfar.a'), 'w').write(
    '; B65 BASIC - generated from src/obj.a by tools/mkobjfar.py: do not edit\n' + text + '\n')
print('src/objfar.a: %d lines' % text.count('\n'))
